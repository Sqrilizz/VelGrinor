export type TranslationParams = Record<string, string | number>;

let activeLanguage: Language = "en";

function interpolate(value: string, params?: TranslationParams): string {
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (match, name: string) => {
    const replacement = params[name];
    return replacement === undefined ? match : String(replacement);
  });
}

function translateValue(value: string, params?: TranslationParams): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim().replace(/\s+/g, " ");
  if (!source) return value;
  const exact = ru[source];
  if (exact) return `${leading}${interpolate(exact, params)}${trailing}`;
  const patterns: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Version (.+)$/, (version) => `Версия ${version}`],
    [/^(\d+) updates? available$/, (count) => `Доступно обновлений: ${count}`],
    [/^(\d+) errors? during check$/, (count) => `Ошибок при проверке: ${count}`],
    [/^Remove (.+)\?$/, (name) => `Удалить ${name}?`],
    [/^Delete (.+)\?$/, (name) => `Удалить ${name}?`],
    [/^Apply "(.+)"$/, (name) => `Применить «${name}»`],
    [/^Java (\d+) is required$/, (version) => `Требуется Java ${version}`],
    [/^Resolving Minecraft (.+)$/, (version) => `Подготовка Minecraft ${version}`],
    [/^Game client (\d+\/\d+): (.+)$/, (count, name) => `Клиент игры ${count}: ${name}`],
    [/^Asset index: (.+)$/, (name) => `Индекс ресурсов: ${name}`],
    [/^Assets (\d+\/\d+): (.+)$/, (count, name) => `Ресурсы ${count}: ${name}`],
    [/^Libraries (\d+\/\d+): (.+)$/, (count, name) => `Библиотеки ${count}: ${name}`],
    [/^Creating profile (.+)$/, (name) => `Создание профиля ${name}`],
    [/^Downloading files (\d+\/\d+): (.+)$/, (count, name) => `Загрузка файлов ${count}: ${name}`],
    [/^(Queued|Preparing|Launching|Running|Done|Error): (.+)$/, (stage, message) => `${ru[stage] ?? stage}: ${translateValue(message)}`],
  ];
  for (const [pattern, formatter] of patterns) {
    const match = source.match(pattern);
    if (match) return `${leading}${formatter(...match.slice(1))}${trailing}`;
  }
  return interpolate(value, params);
}

export function t(key: string, params?: TranslationParams): string {
  return activeLanguage === "ru" ? translateValue(key, params) : interpolate(key, params);
}

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (value: string, params?: TranslationParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === "ru" ? "ru" : "en";
  });
  activeLanguage = language;
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage: setLanguageState,
    toggleLanguage: () => setLanguageState((current) => current === "en" ? "ru" : "en"),
    t: (text, params) => language === "ru" ? translateValue(text, params) : interpolate(text, params),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
